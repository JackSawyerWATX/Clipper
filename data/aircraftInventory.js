// Helper functions for inventory management
export const getPartsByCategory = (category) => {
  return fullInventory.filter(part => part.category === category);
};

export const getLowStockParts = () => {
  return fullInventory.filter(part => part.inStock <= part.minimumStock);
};

export const getPartById = (id) => {
  return fullInventory.find(part => part.id === id);
};

export const searchParts = (searchTerm) => {
  const term = searchTerm.toLowerCase();
  return fullInventory.filter(part => 
    part.name.toLowerCase().includes(term) ||
    part.manufacturer.toLowerCase().includes(term) ||
    part.partNumber.toLowerCase().includes(term) ||
    part.description.toLowerCase().includes(term)
  );
};

export const getCategories = () => {
  return [...new Set(fullInventory.map(part => part.category))];
};

export const getTotalInventoryValue = () => {
  return fullInventory.reduce((total, part) => total + (part.price * part.inStock), 0);
};